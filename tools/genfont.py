rows = []
for c in range(32, 127):
    art = G.get(chr(c))
    assert art is not None, f"missing glyph for {chr(c)!r} ({c})"
    bits = 0
    for y, r in enumerate(art):
        for x, p in enumerate(r):
            if p == '#': bits |= 1 << (y * 5 + x)
    rows.append(bits)

body = []
for i in range(0, len(rows), 8):
    body.append("        " + ", ".join(f"0x{v:09X}UL" for v in rows[i:i+8]) + ",")

