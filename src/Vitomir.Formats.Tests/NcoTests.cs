using System.Text;

namespace Vitomir.Formats.Tests;

/// <summary>
/// The conversation reader, against a file written the way the shipped ones are — a `//` banner the
/// generator wrote, CRLF endings, tab-indented steps, and the English text in a trailing comment
/// that the engine never sees.
/// </summary>
public class NcoTests
{
    static NcoFile Parse(string text) =>
        NcoFile.Read(Encoding.Latin1.GetBytes(text.ReplaceLineEndings("\r\n")), "Test.nco");

    const string Sample = """
        // *********************************************************************************
        //
        // Test.nco (conversation file)
        //
        // This file has been generated by the Voice DB Exporter.
        //
        // *********************************************************************************

        CONVERSATION: Test 0

        EVENT: ev_0
        	LINE:         Kazi_10_1_103                Kazi
        	ANSWERGOTO:   Player_10_1_115              ev_give
        	ANSWERRETURN: Player_10_1_114              2
        	DELAY:        3

        EVENT: ev_give
        	LINE:         Kazi_10_1_156                Kazi
        	JUMP:         ev_0

        # a hash comment, which the engine drops too

        // Kazi_10_1_103   The words, which live in the strings and not here.
        """;

    [Fact]
    public void One_conversation_with_its_events_in_file_order()
    {
        var file = Parse(Sample);
        Assert.Empty(file.Dropped);
        var talk = Assert.Single(file.Conversations);
        Assert.Equal("Test", talk.Name);
        Assert.Equal(0, talk.Number);
        Assert.Equal(["ev_0", "ev_give"], talk.Events.Select(e => e.Name));
        Assert.NotNull(talk.First);
        Assert.Equal(4, talk.First!.Steps.Count);
    }

    [Fact]
    public void Every_step_reads_the_fields_its_kind_uses_and_no_others()
    {
        var talk = Parse(Sample).Conversation("test")!;      // and the lookup is case-insensitive
        var first = talk.Event("EV_0")!.Steps;

        Assert.Equal(NcoStep.Line, first[0].Kind);
        Assert.Equal("Kazi_10_1_103", first[0].Id);
        Assert.Equal("Kazi", first[0].Speaker);
        Assert.Equal("", first[0].Event);

        Assert.Equal(NcoStep.AnswerGoto, first[1].Kind);
        Assert.Equal("Player_10_1_115", first[1].Id);
        Assert.Equal("ev_give", first[1].Event);
        Assert.Equal("", first[1].Speaker);

        Assert.Equal(NcoStep.AnswerReturn, first[2].Kind);
        Assert.Equal("Player_10_1_114", first[2].Id);
        Assert.Equal(2, first[2].Code);

        Assert.Equal(NcoStep.Delay, first[3].Kind);
        Assert.Equal(3_000, first[3].Pause);          // "3" on the page, three seconds in the engine
        Assert.Equal("", first[3].Id);

        var jump = talk.Event("ev_give")!.Steps[1];
        Assert.Equal(NcoStep.Jump, jump.Kind);
        Assert.Equal("ev_0", jump.Event);
    }

    /// <summary>
    /// **`DELAY:` is seconds on the page and milliseconds in the engine** (read as a float, then
    /// times 1000.0, made positive, then truncated). The truncation is after the multiply, so a
    /// fraction survives it — a `0.5` is 500&#160;ms, not nothing.
    ///
    /// This theory previously asserted the opposite, missing the multiply.
    ///
    /// </summary>
    [Theory]
    [InlineData("3", 3_000)]
    [InlineData("0.5", 500)]
    [InlineData("1.5", 1_500)]
    [InlineData("2.5", 2_500)]
    [InlineData("8", 8_000)]
    [InlineData("-2", 2_000)]      // made positive: a negative wait is still a wait
    public void A_delay_is_read_as_seconds(string written, int kept)
    {
        var file = Parse($"CONVERSATION: T 0\nEVENT: ev_0\n\tDELAY: {written}\n");
        Assert.Empty(file.Dropped);
        Assert.Equal(kept, file.Conversations[0].First!.Steps[0].Pause);
    }

    /// <summary>
    /// Three keywords want an **exact** token count and the engine drops the line otherwise; the
    /// three that take a line id want more than two and read an optional fourth and fifth.
    /// </summary>
    [Theory]
    [InlineData("EVENT: a b")]                 // wants exactly 2
    [InlineData("JUMP: a b")]
    [InlineData("DELAY: 1 2")]
    [InlineData("LINE: onlyone")]              // wants more than 2
    [InlineData("ANSWERGOTO: onlyone")]
    [InlineData("ANSWERRETURN: onlyone")]
    [InlineData("SPEAK: somebody something")]  // not a keyword at all
    public void A_line_the_engine_would_drop_is_dropped(string bad)
    {
        var file = Parse($"CONVERSATION: T 0\nEVENT: ev_0\n\t{bad}\n");
        Assert.Single(file.Dropped);
    }

    [Fact]
    public void The_two_optional_numbers_are_read_when_they_are_there()
    {
        var file = Parse("CONVERSATION: T 0\nEVENT: ev_0\n\tLINE: id who 11 22\n");
        Assert.Empty(file.Dropped);
        var step = file.Conversations[0].First!.Steps[0];
        Assert.Equal(11, step.Flags);
        Assert.Equal(22, step.ExtraMs);
    }

    [Fact]
    public void A_token_longer_than_the_engine_keeps_is_truncated_rather_than_refused()
    {
        string long_ = new('x', NcoFile.TokenLength + 10);
        var file = Parse($"CONVERSATION: T 0\nEVENT: ev_0\n\tLINE: {long_} who\n");
        Assert.Empty(file.Dropped);
        Assert.Equal(NcoFile.TokenLength, file.Conversations[0].First!.Steps[0].Id.Length);
    }

    /// <summary>A file may hold more than one conversation; the loader keeps them all by name.</summary>
    [Fact]
    public void More_than_one_conversation_in_a_file_is_kept()
    {
        var file = Parse("CONVERSATION: A 0\nEVENT: ev_0\n\tLINE: a Christof\n"
                       + "CONVERSATION: B 0\nEVENT: ev_0\n\tLINE: b Wilhem\n");
        Assert.Empty(file.Dropped);
        Assert.Equal(2, file.Conversations.Count);
        Assert.Equal("Christof", file.Conversation("A")!.First!.Steps[0].Speaker);
        Assert.Equal("Wilhem", file.Conversation("B")!.First!.Steps[0].Speaker);
    }

    // ---- and the whole shipped corpus ---------------------------------------------------------

    /// <summary>
    /// **All 310 of them, and the vocabulary is complete**: nothing is dropped, every file holds
    /// exactly one conversation named after itself, and every conversation has an `ev_0` to start
    /// at. That last is not a format rule — nothing in the parser requires it — it is what the data
    /// does, and it is what makes "begin a conversation" well defined.
    /// </summary>
    [Fact]
    public void Every_shipped_conversation_parses_with_nothing_left_over()
    {
        using var nob = GameData.Open("Resource.nob");
        int files = 0, steps = 0;
        var problems = new List<string>();
        foreach (var name in nob.NamesWithExtension(".nco"))
        {
            var file = NcoFile.Read(nob.Read(name), name);
            files++;
            if (file.Dropped.Count > 0) problems.Add($"{name}: dropped {file.Dropped[0]}");
            if (file.Conversations.Count != 1) { problems.Add($"{name}: {file.Conversations.Count} conversations"); continue; }
            var talk = file.Conversations[0];
            if (!string.Equals(talk.Name, file.Name, StringComparison.OrdinalIgnoreCase))
                problems.Add($"{name}: named {talk.Name}");
            if (talk.Number != 0) problems.Add($"{name}: number {talk.Number}");
            if (talk.First is null) problems.Add($"{name}: no {NcoConversation.Start}");
            foreach (var e in talk.Events) steps += e.Steps.Count;
        }
        Assert.Empty(problems);
        Assert.Equal(310, files);
        // 2,518 content lines, less the 310 CONVERSATION: and 386 EVENT: headers, which are not steps:
        // 1,651 LINE + 89 ANSWERGOTO + 20 ANSWERRETURN + 58 DELAY + 4 JUMP.
        Assert.Equal(1_822, steps);
    }

    /// <summary>
    /// Every `ANSWERGOTO:` and `JUMP:` names an event **in its own conversation**. A conversation is
    /// a closed graph; nothing reaches into another file.
    /// </summary>
    [Fact]
    public void Every_jump_and_every_reply_lands_on_an_event_that_exists()
    {
        using var nob = GameData.Open("Resource.nob");
        var dangling = new List<string>();
        foreach (var name in nob.NamesWithExtension(".nco"))
            foreach (var talk in NcoFile.Read(nob.Read(name), name).Conversations)
                foreach (var e in talk.Events)
                    foreach (var step in e.Steps)
                        if (step.Kind is NcoStep.Jump or NcoStep.AnswerGoto && talk.Event(step.Event) is null)
                            dangling.Add($"{name}: {e.Name} -> {step.Event}");
        Assert.Empty(dangling);
    }
}
